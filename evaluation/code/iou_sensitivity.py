"""Evaluate matching-threshold sensitivity from frozen instance masks.

The command reuses the threshold-aware one-to-one assignment implemented by
``unified_evaluation.py``. It does not perform inference, train a classifier,
or select a preferred threshold from MI05.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import pandas as pd

from code.unified_evaluation import (
    DetectionCounts,
    extract_frame_key,
    match_iou_matrix,
    package_versions,
    pairwise_iou,
    pooled_metrics,
    positive_ids,
    read_mask,
    sha256_file,
    write_json,
)


SYSTEM_ORDER = ("stardist_saved", "cellpose_auto", "cellpose_fixed")
DISPLAY_NAMES = {
    "stardist_saved": "StarDist",
    "cellpose_auto": "Cellpose automatic",
    "cellpose_fixed": "Cellpose fixed",
}
PRIMARY_THRESHOLD = 0.5


def parse_source(value: str) -> tuple[str, Path]:
    try:
        name, raw_path = value.split("=", 1)
    except ValueError as exc:
        raise argparse.ArgumentTypeError("Sources must use NAME=PATH") from exc
    if not name:
        raise argparse.ArgumentTypeError("Source name cannot be empty")
    return name, Path(raw_path).resolve()


def collect_masks(root: Path, sequence: str) -> dict[str, Path]:
    if not root.is_dir():
        raise FileNotFoundError(root)
    masks: dict[str, Path] = {}
    for path in sorted(root.glob("*.png")):
        key = extract_frame_key(path)
        if not key.startswith(f"{sequence}_"):
            continue
        if key in masks:
            raise ValueError(f"Duplicate frame key {key} in {root}")
        masks[key] = path.resolve()
    if not masks:
        raise ValueError(f"No {sequence} PNG masks found under {root}")
    return masks


def build_tex_table(frame: pd.DataFrame) -> str:
    lines = [
        "% Generated by code/iou_sensitivity.py from frozen MI05 masks.",
        "\\begin{tabular}{llrrrrrrrr}",
        "\\toprule",
        "Method & IoU & TP & FP & FN & Precision & Recall & F1 & Matched IoU & PQ \\\\",
        "\\midrule",
    ]
    for system_index, system in enumerate(SYSTEM_ORDER):
        subset = frame.loc[frame["system"] == system].sort_values("iou_threshold")
        for row in subset.itertuples(index=False):
            lines.append(
                f"{DISPLAY_NAMES[system]} & {row.iou_threshold:.2f} & "
                f"{row.tp:d} & {row.fp:d} & {row.fn:d} & "
                f"{row.precision:.3f} & {row.recall:.3f} & {row.f1:.3f} & "
                f"{row.mean_matched_iou:.3f} & {row.pq:.3f} \\\\" 
            )
        if system_index < len(SYSTEM_ORDER) - 1:
            lines.append("\\addlinespace")
    lines.extend(("\\bottomrule", "\\end{tabular}"))
    return "\n".join(lines) + "\n"


def validate_primary_rows(frame: pd.DataFrame, reference_root: Path) -> dict[str, Any]:
    fields = ("tp", "fp", "fn", "precision", "recall", "f1", "pq")
    validations: dict[str, Any] = {}
    for system in SYSTEM_ORDER:
        reference_path = reference_root / system / "metrics_summary.json"
        reference = json.loads(reference_path.read_text(encoding="utf-8"))["pooled"]
        selected = frame.loc[
            (frame["system"] == system)
            & np.isclose(frame["iou_threshold"], PRIMARY_THRESHOLD)
        ]
        if len(selected) != 1:
            raise ValueError(f"Expected one primary row for {system}, found {len(selected)}")
        row = selected.iloc[0]
        checked: dict[str, bool] = {}
        for field in fields:
            actual = float(row[field])
            expected = float(reference[field])
            checked[field] = bool(np.isclose(actual, expected, rtol=0, atol=1e-12))
        checked["mean_matched_iou"] = bool(
            np.isclose(
                float(row["mean_matched_iou"]),
                float(reference["matched_iou"]),
                rtol=0,
                atol=1e-12,
            )
        )
        if not all(checked.values()):
            raise ValueError(f"Primary IoU 0.50 metrics disagree for {system}: {checked}")
        validations[system] = {
            "reference": str(reference_path.resolve()),
            "reference_sha256": sha256_file(reference_path),
            "checks": checked,
        }
    return validations


def validate_monotonic_counts(frame: pd.DataFrame) -> dict[str, bool]:
    checks: dict[str, bool] = {}
    for system in SYSTEM_ORDER:
        subset = frame.loc[frame["system"] == system].sort_values("iou_threshold")
        tp = subset["tp"].to_numpy()
        fp = subset["fp"].to_numpy()
        fn = subset["fn"].to_numpy()
        valid = bool(np.all(np.diff(tp) <= 0) and np.all(np.diff(fp) >= 0) and np.all(np.diff(fn) >= 0))
        if not valid:
            raise ValueError(f"Matching counts are not monotonic for {system}")
        checks[system] = valid
    return checks


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ground-truth-root", required=True)
    parser.add_argument("--prediction-source", action="append", required=True, type=parse_source)
    parser.add_argument("--reference-results-root", required=True)
    parser.add_argument("--sequence", default="MI05")
    parser.add_argument("--threshold", action="append", required=True, type=float)
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args(argv)

    sequence = args.sequence.upper()
    thresholds = sorted(set(float(value) for value in args.threshold))
    if not thresholds or any(value < 0 or value > 1 for value in thresholds):
        raise ValueError("Thresholds must be unique values in [0, 1]")
    if PRIMARY_THRESHOLD not in thresholds:
        raise ValueError("The primary IoU threshold 0.50 must be included")

    sources = dict(args.prediction_source)
    if tuple(sources) != SYSTEM_ORDER:
        raise ValueError(f"Prediction sources must be supplied in this order: {SYSTEM_ORDER}")

    ground_truth = collect_masks(Path(args.ground_truth_root).resolve(), sequence)
    if len(ground_truth) != 69:
        raise ValueError(f"Expected 69 {sequence} ground-truth frames, found {len(ground_truth)}")

    prediction_maps = {name: collect_masks(root, sequence) for name, root in sources.items()}
    for name, masks in prediction_maps.items():
        if set(masks) != set(ground_truth):
            missing = sorted(set(ground_truth) - set(masks))
            extra = sorted(set(masks) - set(ground_truth))
            raise ValueError(f"Frame mismatch for {name}: missing={missing}, extra={extra}")

    cached: dict[str, list[tuple[str, np.ndarray, np.ndarray, np.ndarray]]] = {}
    input_paths = list(ground_truth.values())
    for system in SYSTEM_ORDER:
        records: list[tuple[str, np.ndarray, np.ndarray, np.ndarray]] = []
        for key in sorted(ground_truth):
            gt_mask = read_mask(ground_truth[key])
            pred_mask = read_mask(prediction_maps[system][key])
            gt_ids, pred_ids, matrix = pairwise_iou(gt_mask, pred_mask)
            records.append((key, gt_ids, pred_ids, matrix))
        cached[system] = records
        input_paths.extend(prediction_maps[system].values())

    rows: list[dict[str, Any]] = []
    for system in SYSTEM_ORDER:
        for threshold in thresholds:
            frame_counts: list[DetectionCounts] = []
            matched_ious: list[float] = []
            for _, gt_ids, pred_ids, matrix in cached[system]:
                matches = match_iou_matrix(gt_ids, pred_ids, matrix, threshold)
                matched_ious.extend(match.iou for match in matches)
                frame_counts.append(
                    DetectionCounts(
                        tp=len(matches),
                        fp=len(pred_ids) - len(matches),
                        fn=len(gt_ids) - len(matches),
                        matched_iou_sum=float(sum(match.iou for match in matches)),
                        matched_iou_count=len(matches),
                    )
                )
            pooled = pooled_metrics(frame_counts)
            rows.append(
                {
                    "system": system,
                    "sequence": sequence,
                    "iou_threshold": threshold,
                    "tp": int(pooled["tp"]),
                    "fp": int(pooled["fp"]),
                    "fn": int(pooled["fn"]),
                    "precision": float(pooled["precision"]),
                    "recall": float(pooled["recall"]),
                    "f1": float(pooled["f1"]),
                    "mean_matched_iou": float(pooled["matched_iou"]),
                    "median_matched_iou": float(np.median(matched_ious)),
                    "pq": float(pooled["pq"]),
                    "matched_iou_support": int(pooled["matched_iou_count"]),
                    "ground_truth_total": int(pooled["tp"] + pooled["fn"]),
                    "predicted_total": int(pooled["tp"] + pooled["fp"]),
                }
            )

    frame = pd.DataFrame(rows)
    frame["system"] = pd.Categorical(frame["system"], categories=SYSTEM_ORDER, ordered=True)
    frame = frame.sort_values(["system", "iou_threshold"], kind="stable").reset_index(drop=True)
    frame["system"] = frame["system"].astype("object")

    reference_root = Path(args.reference_results_root).resolve()
    primary_validation = validate_primary_rows(frame, reference_root)
    monotonic_validation = validate_monotonic_counts(frame)

    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    metrics_path = output_dir / "iou_sensitivity_metrics.csv"
    tex_path = output_dir / "iou_sensitivity_table.tex"
    frame.to_csv(metrics_path, index=False, lineterminator="\n", float_format="%.10g")
    tex_path.write_text(build_tex_table(frame), encoding="utf-8", newline="\n")

    manifest_path = output_dir / "analysis_manifest.json"
    write_json(
        manifest_path,
        {
            "schema_version": "1.0",
            "status": "verified matching-threshold sensitivity from frozen prediction masks",
            "sequence": sequence,
            "thresholds": thresholds,
            "primary_threshold": PRIMARY_THRESHOLD,
            "matching": "threshold-aware optimal one-to-one assignment; maximize eligible match count, then total IoU",
            "aggregation": "pooled TP, FP, FN and matched-IoU support across 69 frames",
            "interpretation": "retrospective MI05 sensitivity analysis; no model or configuration selection",
            "command": [str(Path(sys.argv[0]).resolve()), *sys.argv[1:]],
            "script": {
                "path": str(Path(__file__).resolve()),
                "sha256": sha256_file(Path(__file__).resolve()),
            },
            "packages": package_versions(),
            "validations": {
                "primary_rows_match_verified_results": primary_validation,
                "counts_monotonic_with_threshold": monotonic_validation,
            },
            "inputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in sorted(set(input_paths))
            ],
            "outputs": [
                {"path": str(path), "sha256": sha256_file(path)}
                for path in (metrics_path, tex_path)
            ],
        },
    )


if __name__ == "__main__":
    main()
