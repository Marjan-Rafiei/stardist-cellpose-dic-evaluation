"""Analyze classifier correctness transitions from GT to predicted morphology.

The command uses accepted matched-instance outputs only. It performs no model
inference, classifier fitting, threshold tuning, or feature-domain analysis.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import pandas as pd

from code.unified_evaluation import package_versions, sha256_file, write_json


SYSTEM_ORDER = ("stardist_saved", "cellpose_auto", "cellpose_fixed")
DISPLAY_NAMES = {
    "stardist_saved": "StarDist",
    "cellpose_auto": "Cellpose automatic",
    "cellpose_fixed": "Cellpose fixed",
}
TRANSITION_ORDER = (
    "correct_to_correct",
    "correct_to_incorrect",
    "incorrect_to_incorrect",
    "incorrect_to_correct",
)
TRANSITION_LABELS = {
    "correct_to_correct": "correct to correct",
    "correct_to_incorrect": "correct to incorrect",
    "incorrect_to_incorrect": "incorrect to incorrect",
    "incorrect_to_correct": "incorrect to correct",
}


def transition_label(gt_shape_correct: bool, pred_shape_correct: bool) -> str:
    if gt_shape_correct and pred_shape_correct:
        return "correct_to_correct"
    if gt_shape_correct and not pred_shape_correct:
        return "correct_to_incorrect"
    if not gt_shape_correct and not pred_shape_correct:
        return "incorrect_to_incorrect"
    return "incorrect_to_correct"


def build_tex_table(frame: pd.DataFrame) -> str:
    lines = [
        "% Generated by code/classification_transition_analysis.py.",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Method & C to C & C to I & I to I & I to C & GT-shape accuracy & Pred-shape accuracy \\\\",
        "\\midrule",
    ]
    for row in frame.itertuples(index=False):
        lines.append(
            f"{DISPLAY_NAMES[row.system]} & {row.correct_to_correct:d} & "
            f"{row.correct_to_incorrect:d} & {row.incorrect_to_incorrect:d} & "
            f"{row.incorrect_to_correct:d} & {row.gt_shape_accuracy:.3f} & "
            f"{row.pred_shape_accuracy:.3f} \\\\" 
        )
    lines.extend(("\\bottomrule", "\\end{tabular}"))
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-root", required=True)
    parser.add_argument("--sequence", default="MI05")
    parser.add_argument("--error-chain-summary", required=True)
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args(argv)

    root = Path(args.results_root).resolve()
    sequence = args.sequence.upper()
    error_chain_path = Path(args.error_chain_summary).resolve()
    error_chain = pd.read_csv(error_chain_path).set_index("system")
    output_dir = Path(args.output_dir).resolve()
    input_paths: list[Path] = [error_chain_path]
    transition_rows: list[dict[str, Any]] = []
    class_rows: list[dict[str, Any]] = []
    summary_rows: list[dict[str, Any]] = []
    validations: dict[str, Any] = {}

    for system in SYSTEM_ORDER:
        system_dir = root / system
        matches_path = system_dir / "matched_instances.csv"
        errors_path = system_dir / "error_cases.csv"
        classifier_path = system_dir / "classifier_metrics.json"
        input_paths.extend((matches_path, errors_path, classifier_path))

        matches = pd.read_csv(matches_path)
        matches = matches.loc[matches["frame_id"].str.startswith(f"{sequence}_")].copy()
        errors = pd.read_csv(errors_path)
        errors = errors.loc[errors["frame_id"].str.startswith(f"{sequence}_")].copy()
        classifier = json.loads(classifier_path.read_text(encoding="utf-8"))
        if matches.empty:
            raise ValueError(f"No matched instances found for {system}")

        matches["transition"] = [
            transition_label(bool(start), bool(end))
            for start, end in zip(
                matches["gt_classifier_correct"], matches["class_correct"], strict=True
            )
        ]
        counts = matches["transition"].value_counts().to_dict()
        for transition in TRANSITION_ORDER:
            count = int(counts.get(transition, 0))
            transition_rows.append(
                {
                    "system": system,
                    "transition": transition,
                    "transition_label": TRANSITION_LABELS[transition],
                    "count": count,
                    "percent_of_matches": count / len(matches),
                    "gt_shape_correct": transition.startswith("correct_"),
                    "pred_shape_correct": transition.endswith("_correct"),
                }
            )

        for gt_class, class_name in ((1, "interphase"), (2, "mitotic")):
            subset = matches.loc[matches["gt_class"] == gt_class]
            class_counts = subset["transition"].value_counts().to_dict()
            for transition in TRANSITION_ORDER:
                count = int(class_counts.get(transition, 0))
                class_rows.append(
                    {
                        "system": system,
                        "gt_class": gt_class,
                        "gt_class_name": class_name,
                        "transition": transition,
                        "count": count,
                        "class_support": len(subset),
                        "percent_within_class": count / len(subset),
                    }
                )

        correct_to_correct = int(counts.get("correct_to_correct", 0))
        correct_to_incorrect = int(counts.get("correct_to_incorrect", 0))
        incorrect_to_incorrect = int(counts.get("incorrect_to_incorrect", 0))
        incorrect_to_correct = int(counts.get("incorrect_to_correct", 0))
        gt_shape_correct = correct_to_correct + correct_to_incorrect
        pred_shape_correct = correct_to_correct + incorrect_to_correct
        gt_shape_accuracy = gt_shape_correct / len(matches)
        pred_shape_accuracy = pred_shape_correct / len(matches)
        output_changes = correct_to_incorrect + incorrect_to_correct

        summary_rows.append(
            {
                "system": system,
                "matched_instances": len(matches),
                "correct_to_correct": correct_to_correct,
                "correct_to_incorrect": correct_to_incorrect,
                "incorrect_to_incorrect": incorrect_to_incorrect,
                "incorrect_to_correct": incorrect_to_correct,
                "gt_shape_correct": gt_shape_correct,
                "pred_shape_correct": pred_shape_correct,
                "gt_shape_accuracy": gt_shape_accuracy,
                "pred_shape_accuracy": pred_shape_accuracy,
                "accuracy_change": pred_shape_accuracy - gt_shape_accuracy,
                "accuracy_change_percentage_points": 100 * (
                    pred_shape_accuracy - gt_shape_accuracy
                ),
                "classifier_output_changes": output_changes,
                "net_correct_count_change": incorrect_to_correct - correct_to_incorrect,
            }
        )

        narrow_error_rows = int(
            (errors["error_type"] == "segmentation_induced_class_flip").sum()
        )
        persistent_error_rows = int(
            (errors["error_type"] == "classifier_error_present_on_ground_truth_shape").sum()
        )
        step8_output_changes = int(
            error_chain.loc[system, "morphology_induced_class_changes"]
        )
        checks = {
            "four_categories_sum_to_matches": (
                correct_to_correct
                + correct_to_incorrect
                + incorrect_to_incorrect
                + incorrect_to_correct
                == len(matches)
            ),
            "gt_shape_accuracy_matches_raw_flag": bool(
                np.isclose(
                    gt_shape_accuracy,
                    matches["gt_classifier_correct"].mean(),
                    rtol=0,
                    atol=1e-12,
                )
            ),
            "pred_shape_accuracy_matches_raw_flag": bool(
                np.isclose(
                    pred_shape_accuracy,
                    matches["class_correct"].mean(),
                    rtol=0,
                    atol=1e-12,
                )
            ),
            "pred_shape_accuracy_matches_classifier_summary": bool(
                np.isclose(
                    pred_shape_accuracy,
                    classifier["classification_only"]["accuracy"],
                    rtol=0,
                    atol=1e-12,
                )
            ),
            "correct_to_incorrect_matches_historical_flip_flag": (
                correct_to_incorrect == int(matches["segmentation_induced_flip"].sum())
            ),
            "correct_to_incorrect_matches_error_rows": (
                correct_to_incorrect == narrow_error_rows
            ),
            "incorrect_to_incorrect_matches_persistent_error_rows": (
                incorrect_to_incorrect == persistent_error_rows
            ),
            "output_changes_match_step8": output_changes == step8_output_changes,
            "accuracy_change_matches_transition_balance": bool(
                np.isclose(
                    pred_shape_accuracy - gt_shape_accuracy,
                    (incorrect_to_correct - correct_to_incorrect) / len(matches),
                    rtol=0,
                    atol=1e-12,
                )
            ),
        }
        if not all(checks.values()):
            raise ValueError(f"Transition reconciliation failed for {system}: {checks}")
        validations[system] = checks

    summary_frame = pd.DataFrame(summary_rows)
    summary_frame["system"] = pd.Categorical(
        summary_frame["system"], categories=SYSTEM_ORDER, ordered=True
    )
    summary_frame = summary_frame.sort_values("system", kind="stable").reset_index(drop=True)
    summary_frame["system"] = summary_frame["system"].astype("object")
    transitions_frame = pd.DataFrame(transition_rows)
    class_frame = pd.DataFrame(class_rows)

    output_dir.mkdir(parents=True, exist_ok=True)
    summary_path = output_dir / "transition_summary.csv"
    transitions_path = output_dir / "transition_counts.csv"
    class_path = output_dir / "transition_by_class.csv"
    tex_path = output_dir / "transition_matrix_table.tex"
    json_path = output_dir / "analysis_summary.json"
    summary_frame.to_csv(summary_path, index=False, lineterminator="\n", float_format="%.10g")
    transitions_frame.to_csv(
        transitions_path, index=False, lineterminator="\n", float_format="%.10g"
    )
    class_frame.to_csv(class_path, index=False, lineterminator="\n", float_format="%.10g")
    tex_path.write_text(build_tex_table(summary_frame), encoding="utf-8", newline="\n")

    write_json(
        json_path,
        {
            "schema_version": "1.0",
            "sequence": sequence,
            "analysis": "classification correctness transition from ground-truth-mask morphology to predicted-mask morphology",
            "systems": {
                row["system"]: {key: value for key, value in row.items() if key != "system"}
                for row in summary_frame.to_dict(orient="records")
            },
            "validations": validations,
            "interpretation": {
                "incorrect_to_correct": "An altered predicted-mask feature vector crossed the locked classifier decision boundary into the annotation class. This is an accidental transition, not a beneficial biological effect.",
                "scope": "Matched MI05 instances only; transitions do not include unmatched annotated or predicted instances.",
                "target": "ALFI annotation-class recovery, with different annotated compartments for interphase and mitotic objects.",
            },
        },
    )

    output_paths = (summary_path, transitions_path, class_path, tex_path, json_path)
    write_json(
        output_dir / "analysis_manifest.json",
        {
            "schema_version": "1.0",
            "status": "verified matched-instance classification transition analysis",
            "sequence": sequence,
            "command": [str(Path(sys.argv[0]).resolve()), *sys.argv[1:]],
            "script": {
                "path": str(Path(__file__).resolve()),
                "sha256": sha256_file(Path(__file__).resolve()),
            },
            "packages": package_versions(),
            "inputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in sorted(input_paths)
            ],
            "outputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in output_paths
            ],
            "actions_performed": {
                "model_inference": False,
                "classifier_fitting": False,
                "threshold_tuning": False,
                "morphology_domain_shift_analysis": False,
            },
        },
    )


if __name__ == "__main__":
    main()
