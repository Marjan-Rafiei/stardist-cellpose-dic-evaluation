"""Audit the locked morphology Random Forest and run one linear benchmark.

The benchmark uses the fixed MI01 to MI03 training split, MI04 validation,
the same eight raw features, median imputation, balanced class weights, and no
MI05 data. No hyperparameter search or probability-threshold tuning is done.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Sequence

import joblib
import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
)
from sklearn.pipeline import Pipeline

from code.train_classifier import collect_rows
from code.unified_evaluation import (
    CLASS_NAMES,
    FEATURE_NAMES,
    package_versions,
    sha256_file,
    write_json,
)


TRAIN_SEQUENCES = ("MI01", "MI02", "MI03")
VALIDATION_SEQUENCE = "MI04"
FORBIDDEN_SEQUENCE = "MI05"
MODEL_ORDER = ("random_forest", "logistic_regression")
DISPLAY_NAMES = {
    "random_forest": "Random Forest",
    "logistic_regression": "Logistic Regression",
}


def evaluate_predictions(
    model_name: str,
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> dict[str, Any]:
    labels = list(CLASS_NAMES)
    report = classification_report(
        y_true,
        y_pred,
        labels=labels,
        target_names=[CLASS_NAMES[label] for label in labels],
        output_dict=True,
        zero_division=0,
    )
    matrix = confusion_matrix(y_true, y_pred, labels=labels)
    return {
        "model": model_name,
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y_true, y_pred)),
        "macro_f1": float(f1_score(y_true, y_pred, labels=labels, average="macro", zero_division=0)),
        "interphase_precision": float(report["interphase"]["precision"]),
        "interphase_recall": float(report["interphase"]["recall"]),
        "interphase_f1": float(report["interphase"]["f1-score"]),
        "mitotic_precision": float(report["mitotic"]["precision"]),
        "mitotic_recall": float(report["mitotic"]["recall"]),
        "mitotic_f1": float(report["mitotic"]["f1-score"]),
        "cm_interphase_as_interphase": int(matrix[0, 0]),
        "cm_interphase_as_mitotic": int(matrix[0, 1]),
        "cm_mitotic_as_interphase": int(matrix[1, 0]),
        "cm_mitotic_as_mitotic": int(matrix[1, 1]),
    }


def feature_distributions(frame: pd.DataFrame, split: str) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for class_id, class_name in CLASS_NAMES.items():
        subset = frame.loc[frame["target"] == class_id]
        for feature in FEATURE_NAMES:
            values = subset[feature].to_numpy(dtype=float)
            rows.append(
                {
                    "split": split,
                    "class_id": class_id,
                    "class_name": class_name,
                    "feature": feature,
                    "count": len(values),
                    "mean": float(np.mean(values)),
                    "std": float(np.std(values, ddof=1)) if len(values) > 1 else 0.0,
                    "median": float(np.median(values)),
                    "q25": float(np.quantile(values, 0.25)),
                    "q75": float(np.quantile(values, 0.75)),
                }
            )
    return rows


def correlation_rows(frame: pd.DataFrame, split: str) -> list[dict[str, Any]]:
    matrix = frame.loc[:, FEATURE_NAMES].corr(method="spearman")
    rows: list[dict[str, Any]] = []
    for first_index, first in enumerate(FEATURE_NAMES):
        for second in FEATURE_NAMES[first_index + 1 :]:
            rows.append(
                {
                    "split": split,
                    "feature_a": first,
                    "feature_b": second,
                    "spearman_correlation": float(matrix.loc[first, second]),
                    "absolute_spearman_correlation": float(abs(matrix.loc[first, second])),
                }
            )
    return rows


def build_tex_table(frame: pd.DataFrame) -> str:
    lines = [
        "% Generated by code/random_forest_audit.py.",
        "\\begin{tabular}{lrrrrrrr}",
        "\\toprule",
        "Model & Macro F1 & I precision & I recall & I F1 & M precision & M recall & M F1 \\\\",
        "\\midrule",
    ]
    for row in frame.itertuples(index=False):
        lines.append(
            f"{DISPLAY_NAMES[row.model]} & {row.macro_f1:.3f} & "
            f"{row.interphase_precision:.3f} & {row.interphase_recall:.3f} & "
            f"{row.interphase_f1:.3f} & {row.mitotic_precision:.3f} & "
            f"{row.mitotic_recall:.3f} & {row.mitotic_f1:.3f} \\\\" 
        )
    lines.extend(("\\bottomrule", "\\end{tabular}"))
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset-root", required=True)
    parser.add_argument("--config", required=True)
    parser.add_argument("--classifier", required=True)
    parser.add_argument("--classifier-manifest", required=True)
    parser.add_argument("--training-rows", required=True)
    parser.add_argument("--validation-predictions", required=True)
    parser.add_argument("--dataset-manifest", required=True)
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args(argv)

    dataset_root = Path(args.dataset_root).resolve()
    config_path = Path(args.config).resolve()
    classifier_path = Path(args.classifier).resolve()
    classifier_manifest_path = Path(args.classifier_manifest).resolve()
    training_rows_path = Path(args.training_rows).resolve()
    validation_predictions_path = Path(args.validation_predictions).resolve()
    dataset_manifest_path = Path(args.dataset_manifest).resolve()
    output_dir = Path(args.output_dir).resolve()

    config = json.loads(config_path.read_text(encoding="utf-8"))
    classifier_manifest = json.loads(classifier_manifest_path.read_text(encoding="utf-8"))
    dataset_manifest = json.loads(dataset_manifest_path.read_text(encoding="utf-8"))
    random_forest = joblib.load(classifier_path)

    train = collect_rows(dataset_root, TRAIN_SEQUENCES)
    validation = collect_rows(dataset_root, (VALIDATION_SEQUENCE,))
    saved_training_rows = pd.read_csv(training_rows_path)
    saved_validation = pd.read_csv(validation_predictions_path)
    feature_columns = list(FEATURE_NAMES)

    x_train = train.loc[:, FEATURE_NAMES]
    y_train = train["target"].astype(int).to_numpy()
    x_validation = validation.loc[:, FEATURE_NAMES]
    y_validation = validation["target"].astype(int).to_numpy()

    rf_predicted = random_forest.predict(x_validation).astype(int)
    rf_probabilities = random_forest.predict_proba(x_validation)
    rf_mitotic_column = int(np.flatnonzero(random_forest.classes_ == 2)[0])

    logistic = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            (
                "classifier",
                LogisticRegression(
                    penalty=None,
                    class_weight="balanced",
                    random_state=42,
                    solver="lbfgs",
                    max_iter=50000,
                    tol=1e-9,
                ),
            ),
        ]
    )
    logistic.fit(x_train, y_train)
    logistic_predicted = logistic.predict(x_validation).astype(int)
    logistic_probabilities = logistic.predict_proba(x_validation)
    logistic_mitotic_column = int(np.flatnonzero(logistic.classes_ == 2)[0])

    benchmark_rows = [
        evaluate_predictions("random_forest", y_validation, rf_predicted),
        evaluate_predictions("logistic_regression", y_validation, logistic_predicted),
    ]
    benchmark_frame = pd.DataFrame(benchmark_rows)

    class_balance_rows: list[dict[str, Any]] = []
    for split, frame in (("training", train), ("validation", validation)):
        groups = [("all", frame), *[(sequence, frame.loc[frame["sequence"] == sequence]) for sequence in sorted(frame["sequence"].unique())]]
        for sequence, subset in groups:
            total = len(subset)
            for class_id, class_name in CLASS_NAMES.items():
                count = int((subset["target"] == class_id).sum())
                class_balance_rows.append(
                    {
                        "split": split,
                        "sequence": sequence,
                        "class_id": class_id,
                        "class_name": class_name,
                        "count": count,
                        "fraction": count / total,
                        "total": total,
                    }
                )

    distribution_frame = pd.DataFrame(
        [
            *feature_distributions(train, "training"),
            *feature_distributions(validation, "validation"),
        ]
    )
    correlation_frame = pd.DataFrame(
        [*correlation_rows(train, "training"), *correlation_rows(validation, "validation")]
    )
    coefficient_frame = pd.DataFrame(
        {
            "feature": FEATURE_NAMES,
            "coefficient_for_mitotic_log_odds": logistic.named_steps["classifier"].coef_[0],
        }
    )

    validation_keys = validation.loc[:, ["sequence", "frame_id", "instance_id", "target"]].reset_index(drop=True)
    prediction_frame = validation_keys.assign(
        random_forest_predicted=rf_predicted,
        random_forest_mitotic_probability=rf_probabilities[:, rf_mitotic_column],
        logistic_regression_predicted=logistic_predicted,
        logistic_regression_mitotic_probability=logistic_probabilities[:, logistic_mitotic_column],
    )

    reconstructed_training_rows = train.loc[:, ["sequence", "frame_id", "instance_id", "target"]].reset_index(drop=True)
    saved_training_rows = saved_training_rows.loc[:, reconstructed_training_rows.columns].reset_index(drop=True)
    saved_validation_expected = validation.loc[:, ["sequence", "frame_id", "instance_id", *FEATURE_NAMES, "target"]].reset_index(drop=True)
    saved_validation_selected = saved_validation.loc[:, saved_validation_expected.columns].reset_index(drop=True)
    rf_pipeline = random_forest.named_steps
    rf_classifier = rf_pipeline["classifier"]
    rf_imputer = rf_pipeline["imputer"]
    expected_rf_parameters = config["classifier"]

    missing_train = x_train.isna().sum().astype(int).to_dict()
    missing_validation = x_validation.isna().sum().astype(int).to_dict()
    nonfinite_train = int((~np.isfinite(x_train.to_numpy(dtype=float))).sum())
    nonfinite_validation = int((~np.isfinite(x_validation.to_numpy(dtype=float))).sum())
    validations = {
        "config_training_sequences_exact": tuple(config["training_sequences"]) == TRAIN_SEQUENCES,
        "config_validation_sequence_exact": config["validation_sequences"] == [VALIDATION_SEQUENCE],
        "config_test_sequence_is_mi05": config["test_sequences"] == [FORBIDDEN_SEQUENCE],
        "feature_order_exact": tuple(config["features"]) == FEATURE_NAMES,
        "no_mi05_in_training_or_validation": not (
            (train["sequence"] == FORBIDDEN_SEQUENCE).any()
            or (validation["sequence"] == FORBIDDEN_SEQUENCE).any()
        ),
        "training_rows_match_saved": reconstructed_training_rows.equals(saved_training_rows),
        "validation_identifiers_and_targets_match_saved": saved_validation_expected.loc[:, ["sequence", "frame_id", "instance_id", "target"]].equals(
            saved_validation_selected.loc[:, ["sequence", "frame_id", "instance_id", "target"]]
        ),
        "validation_features_match_saved": bool(
            np.allclose(
                saved_validation_expected.loc[:, FEATURE_NAMES],
                saved_validation_selected.loc[:, FEATURE_NAMES],
                rtol=0,
                atol=1e-7,
            )
        ),
        "rf_predictions_match_saved": bool(
            np.array_equal(rf_predicted, saved_validation["predicted"].to_numpy(dtype=int))
        ),
        "no_duplicate_training_instances": not train.duplicated(["sequence", "frame_id", "instance_id"]).any(),
        "no_duplicate_validation_instances": not validation.duplicated(["sequence", "frame_id", "instance_id"]).any(),
        "no_missing_training_features": sum(missing_train.values()) == 0,
        "no_missing_validation_features": sum(missing_validation.values()) == 0,
        "all_training_features_finite": nonfinite_train == 0,
        "all_validation_features_finite": nonfinite_validation == 0,
        "rf_pipeline_steps_exact": list(rf_pipeline) == ["imputer", "classifier"],
        "rf_imputer_is_median": rf_imputer.strategy == "median",
        "rf_n_estimators_match_config": rf_classifier.n_estimators == expected_rf_parameters["n_estimators"],
        "rf_class_weight_matches_config": rf_classifier.class_weight == expected_rf_parameters["class_weight"],
        "rf_seed_matches_config": rf_classifier.random_state == expected_rf_parameters["random_state"],
        "rf_n_jobs_match_config": rf_classifier.n_jobs == expected_rf_parameters["n_jobs"],
        "classifier_hash_matches_manifest": sha256_file(classifier_path) == classifier_manifest["classifier"]["sha256"],
        "training_rows_hash_matches_manifest": sha256_file(training_rows_path) == classifier_manifest["training_rows_sha256"],
        "validation_hash_matches_manifest": sha256_file(validation_predictions_path) == classifier_manifest["validation_predictions_sha256"],
        "dataset_audit_has_no_blocking_issue": dataset_manifest["blocking_issue_count"] == 0,
    }
    if not all(validations.values()):
        raise ValueError(f"Random Forest audit validation failed: {validations}")

    output_dir.mkdir(parents=True, exist_ok=True)
    benchmark_path = output_dir / "benchmark_metrics.csv"
    predictions_path = output_dir / "benchmark_predictions.csv"
    balance_path = output_dir / "class_balance.csv"
    distributions_path = output_dir / "feature_distributions.csv"
    correlations_path = output_dir / "feature_correlations.csv"
    coefficients_path = output_dir / "logistic_coefficients.csv"
    tex_path = output_dir / "benchmark_table.tex"
    summary_path = output_dir / "audit_summary.json"
    benchmark_frame.to_csv(benchmark_path, index=False, lineterminator="\n", float_format="%.10g")
    prediction_frame.to_csv(predictions_path, index=False, lineterminator="\n", float_format="%.10g")
    pd.DataFrame(class_balance_rows).to_csv(balance_path, index=False, lineterminator="\n", float_format="%.10g")
    distribution_frame.to_csv(distributions_path, index=False, lineterminator="\n", float_format="%.10g")
    correlation_frame.to_csv(correlations_path, index=False, lineterminator="\n", float_format="%.10g")
    coefficient_frame.to_csv(coefficients_path, index=False, lineterminator="\n", float_format="%.10g")
    tex_path.write_text(build_tex_table(benchmark_frame), encoding="utf-8", newline="\n")

    rf_row = benchmark_frame.loc[benchmark_frame["model"] == "random_forest"].iloc[0]
    logistic_row = benchmark_frame.loc[benchmark_frame["model"] == "logistic_regression"].iloc[0]
    strongest_correlations = correlation_frame.sort_values(
        ["split", "absolute_spearman_correlation"], ascending=[True, False], kind="stable"
    ).groupby("split", sort=False).head(6)
    write_json(
        summary_path,
        {
            "schema_version": "1.0",
            "target": {
                "name": "ALFI annotation-class recovery from ground-truth-mask morphology",
                "classes": CLASS_NAMES,
                "assignment": "majority valid class-mask pixels within each ground-truth instance",
                "interpretation_limit": "interphase masks describe nuclei and mitotic masks describe whole-cell regions",
            },
            "split": {
                "training_sequences": list(TRAIN_SEQUENCES),
                "validation_sequence": VALIDATION_SEQUENCE,
                "forbidden_sequence": FORBIDDEN_SEQUENCE,
                "training_frames": int(train["frame_id"].nunique()),
                "validation_frames": int(validation["frame_id"].nunique()),
                "training_instances": len(train),
                "validation_instances": len(validation),
            },
            "missing_values": {
                "training_by_feature": missing_train,
                "validation_by_feature": missing_validation,
                "imputation": "median imputer fitted on MI01 to MI03 only; no missing values were observed, so no value was replaced in the audited data",
            },
            "feature_construction": {
                "source": "scikit-image regionprops on ground-truth instance masks",
                "features": list(FEATURE_NAMES),
                "aspect_ratio": "major_axis_length divided by minor_axis_length; zero only if minor axis is zero",
            },
            "random_forest": {
                "parameters": {
                    "n_estimators": rf_classifier.n_estimators,
                    "class_weight": rf_classifier.class_weight,
                    "random_state": rf_classifier.random_state,
                    "n_jobs": rf_classifier.n_jobs,
                    "other_parameters": "scikit-learn defaults; no documented hyperparameter search",
                },
                "probability_decision": "predict selects the class with highest mean tree probability; no separate probability threshold was tuned",
                "why_used": "handles nonlinear thresholds and feature interactions, accepts mixed-scale raw morphology after median imputation, supports balanced class weights, and provides a deterministic fitted baseline",
                "limitations": "flexible and less interpretable; one validation sequence cannot establish generalization or optimality",
            },
            "logistic_benchmark": {
                "parameters": {
                    "penalty": None,
                    "class_weight": "balanced",
                    "random_state": 42,
                    "solver": "lbfgs",
                    "max_iter": 50000,
                    "tol": 1e-9,
                    "iterations_used": int(logistic.named_steps["classifier"].n_iter_[0]),
                    "intercept": float(logistic.named_steps["classifier"].intercept_[0]),
                },
                "preprocessing": "same median-only imputation and raw feature order as the Random Forest; no scaling and no regularization",
                "selection": "single preregistered-style simple benchmark; no hyperparameter search and no MI05 use",
                "probability_decision": "predict selects the class with highest probability; no threshold was tuned",
            },
            "comparison": {
                "random_forest_macro_f1": float(rf_row["macro_f1"]),
                "logistic_regression_macro_f1": float(logistic_row["macro_f1"]),
                "macro_f1_difference": float(rf_row["macro_f1"] - logistic_row["macro_f1"]),
                "answer": "The Random Forest meaningfully improves MI04 macro F1 over the simple linear benchmark, while Logistic Regression attains higher mitotic recall at the cost of many interphase false positives.",
                "scope": "MI04 validation only; not a model leaderboard and not independent-experiment uncertainty",
            },
            "strongest_feature_correlations": strongest_correlations.to_dict(orient="records"),
            "leakage_audit": {
                "sequence_split": "pass",
                "mi05_used_for_training_validation_or_benchmark": False,
                "cross_sequence_exact_duplicates": "none found in prior dataset audit",
                "remaining_limit": "MI04 is one temporally related sequence and historical MI05 use prevents describing MI05 as pristine unseen test data",
            },
            "validations": validations,
        },
    )

    output_paths = (
        benchmark_path,
        predictions_path,
        balance_path,
        distributions_path,
        correlations_path,
        coefficients_path,
        tex_path,
        summary_path,
    )
    input_paths = (
        config_path,
        classifier_path,
        classifier_manifest_path,
        training_rows_path,
        validation_predictions_path,
        dataset_manifest_path,
    )
    write_json(
        output_dir / "analysis_manifest.json",
        {
            "schema_version": "1.0",
            "status": "verified Random Forest audit and single Logistic Regression benchmark",
            "command": [str(Path(sys.argv[0]).resolve()), *sys.argv[1:]],
            "script": {
                "path": str(Path(__file__).resolve()),
                "sha256": sha256_file(Path(__file__).resolve()),
            },
            "packages": package_versions(),
            "dataset_root": str(dataset_root),
            "inputs": [
                {"path": str(path), "sha256": sha256_file(path)} for path in sorted(input_paths)
            ],
            "outputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in output_paths
            ],
            "actions_performed": {
                "random_forest_retraining": False,
                "logistic_regression_benchmark_fit": True,
                "hyperparameter_search": False,
                "mi05_use": False,
                "probability_threshold_tuning": False,
            },
        },
    )


if __name__ == "__main__":
    main()
