"""Quantify paired morphology domain shift on matched MI05 instances.

This command reads accepted matched-instance tables. It performs no inference,
classifier fitting, threshold tuning, or feature selection.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from code.classification_transition_analysis import transition_label
from code.unified_evaluation import FEATURE_NAMES, package_versions, sha256_file, write_json


SYSTEM_ORDER = ("stardist_saved", "cellpose_auto", "cellpose_fixed")
DISPLAY_NAMES = {
    "stardist_saved": "StarDist",
    "cellpose_auto": "Cellpose automatic",
    "cellpose_fixed": "Cellpose fixed",
}
FEATURE_UNITS = {
    "area": "pixels_squared",
    "perimeter": "pixels",
    "eccentricity": "dimensionless",
    "solidity": "dimensionless",
    "extent": "dimensionless",
    "major_axis_length": "pixels",
    "minor_axis_length": "pixels",
    "aspect_ratio": "dimensionless",
}
SYSTEMATIC_DIRECTION_THRESHOLD = 0.75


def summarize_feature(
    system: str,
    feature: str,
    gt_values: np.ndarray,
    pred_values: np.ndarray,
) -> dict[str, Any]:
    gt_values = np.asarray(gt_values, dtype=float)
    pred_values = np.asarray(pred_values, dtype=float)
    if gt_values.shape != pred_values.shape or gt_values.ndim != 1:
        raise ValueError("paired feature arrays must be one-dimensional with equal shape")
    if len(gt_values) == 0 or not np.isfinite(gt_values).all() or not np.isfinite(pred_values).all():
        raise ValueError("paired feature arrays must be nonempty and finite")
    if np.any(gt_values <= 0):
        raise ValueError("relative differences require positive ground-truth feature values")

    signed = pred_values - gt_values
    absolute = np.abs(signed)
    relative = 100 * signed / gt_values
    absolute_relative = np.abs(relative)
    positive_fraction = float(np.mean(signed > 0))
    negative_fraction = float(np.mean(signed < 0))
    zero_fraction = float(np.mean(signed == 0))
    if positive_fraction >= negative_fraction:
        dominant_direction = "positive"
        direction_consistency = positive_fraction
    else:
        dominant_direction = "negative"
        direction_consistency = negative_fraction
    correlation = float(spearmanr(gt_values, pred_values).statistic)

    return {
        "system": system,
        "feature": feature,
        "unit": FEATURE_UNITS[feature],
        "matched_instances": len(gt_values),
        "gt_mean": float(np.mean(gt_values)),
        "gt_median": float(np.median(gt_values)),
        "gt_q25": float(np.quantile(gt_values, 0.25)),
        "gt_q75": float(np.quantile(gt_values, 0.75)),
        "pred_mean": float(np.mean(pred_values)),
        "pred_median": float(np.median(pred_values)),
        "pred_q25": float(np.quantile(pred_values, 0.25)),
        "pred_q75": float(np.quantile(pred_values, 0.75)),
        "mean_signed_difference": float(np.mean(signed)),
        "median_signed_difference": float(np.median(signed)),
        "sd_signed_difference": float(np.std(signed, ddof=1)),
        "q25_signed_difference": float(np.quantile(signed, 0.25)),
        "q75_signed_difference": float(np.quantile(signed, 0.75)),
        "mean_absolute_difference": float(np.mean(absolute)),
        "median_absolute_difference": float(np.median(absolute)),
        "median_relative_difference_percent": float(np.median(relative)),
        "median_absolute_relative_difference_percent": float(np.median(absolute_relative)),
        "positive_fraction": positive_fraction,
        "negative_fraction": negative_fraction,
        "zero_fraction": zero_fraction,
        "dominant_direction": dominant_direction,
        "direction_consistency": direction_consistency,
        "descriptively_systematic": direction_consistency >= SYSTEMATIC_DIRECTION_THRESHOLD,
        "spearman_correlation": correlation,
    }


def build_tex_table(frame: pd.DataFrame) -> str:
    lines = [
        "% Generated by code/morphology_domain_shift.py.",
        "\\begin{tabular}{lrrrrrrrr}",
        "\\toprule",
        "Method & Area & Perimeter & Eccentricity & Solidity & Extent & Major axis & Minor axis & Aspect ratio \\\\",
        "\\midrule",
    ]
    for system in SYSTEM_ORDER:
        subset = frame.loc[frame["system"] == system].set_index("feature")
        values = [subset.loc[feature, "median_relative_difference_percent"] for feature in FEATURE_NAMES]
        rendered = " & ".join(f"{value:+.1f}\\%" for value in values)
        lines.append(f"{DISPLAY_NAMES[system]} & {rendered} \\\\")
    lines.extend(("\\bottomrule", "\\end{tabular}"))
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-root", required=True)
    parser.add_argument("--sequence", default="MI05")
    parser.add_argument("--transition-summary", required=True)
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args(argv)

    root = Path(args.results_root).resolve()
    sequence = args.sequence.upper()
    transition_summary_path = Path(args.transition_summary).resolve()
    transition_summary = pd.read_csv(transition_summary_path).set_index("system")
    output_dir = Path(args.output_dir).resolve()
    input_paths: list[Path] = [transition_summary_path]
    summary_rows: list[dict[str, Any]] = []
    common_summary_rows: list[dict[str, Any]] = []
    paired_rows: list[dict[str, Any]] = []
    validations: dict[str, Any] = {}

    matches_by_system: dict[str, pd.DataFrame] = {}
    for system in SYSTEM_ORDER:
        matches_path = root / system / "matched_instances.csv"
        input_paths.append(matches_path)
        matches = pd.read_csv(matches_path)
        matches = matches.loc[matches["frame_id"].str.startswith(f"{sequence}_")].copy()
        if matches.empty:
            raise ValueError(f"No matched instances found for {system}")
        matches_by_system[system] = matches

    common_keys = set.intersection(
        *(
            {(row.frame_id, int(row.gt_id)) for row in matches.itertuples(index=False)}
            for matches in matches_by_system.values()
        )
    )
    if not common_keys:
        raise ValueError("No annotated instances are matched by all systems")

    for system in SYSTEM_ORDER:
        matches = matches_by_system[system].copy()
        matches["transition"] = [
            transition_label(bool(start), bool(end))
            for start, end in zip(
                matches["gt_classifier_correct"], matches["class_correct"], strict=True
            )
        ]

        delta_checks: dict[str, bool] = {}
        for feature in FEATURE_NAMES:
            gt = matches[f"gt_{feature}"].to_numpy(dtype=float)
            pred = matches[f"pred_{feature}"].to_numpy(dtype=float)
            stored_delta = matches[f"delta_{feature}"].to_numpy(dtype=float)
            delta_checks[feature] = bool(
                np.allclose(pred - gt, stored_delta, rtol=0, atol=2e-7)
            )
            summary_rows.append(summarize_feature(system, feature, gt, pred))
            for row, gt_value, pred_value in zip(
                matches.itertuples(index=False), gt, pred, strict=True
            ):
                signed = float(pred_value - gt_value)
                relative = 100 * signed / float(gt_value)
                paired_rows.append(
                    {
                        "system": system,
                        "frame_id": row.frame_id,
                        "gt_id": int(row.gt_id),
                        "pred_id": int(row.pred_id),
                        "gt_class": int(row.gt_class),
                        "transition": row.transition,
                        "feature": feature,
                        "unit": FEATURE_UNITS[feature],
                        "gt_value": float(gt_value),
                        "pred_value": float(pred_value),
                        "signed_difference": signed,
                        "absolute_difference": abs(signed),
                        "relative_difference_percent": relative,
                        "absolute_relative_difference_percent": abs(relative),
                    }
                )

        common_matches = matches.loc[
            [
                (row.frame_id, int(row.gt_id)) in common_keys
                for row in matches.itertuples(index=False)
            ]
        ]
        for feature in FEATURE_NAMES:
            common_summary_rows.append(
                summarize_feature(
                    system,
                    feature,
                    common_matches[f"gt_{feature}"].to_numpy(dtype=float),
                    common_matches[f"pred_{feature}"].to_numpy(dtype=float),
                )
            )

        computed_transitions = matches["transition"].value_counts().to_dict()
        transition_checks = {
            transition: int(computed_transitions.get(transition, 0))
            == int(transition_summary.loc[system, transition])
            for transition in (
                "correct_to_correct",
                "correct_to_incorrect",
                "incorrect_to_incorrect",
                "incorrect_to_correct",
            )
        }
        checks = {
            "matched_support_matches_step9": (
                len(matches) == int(transition_summary.loc[system, "matched_instances"])
            ),
            "all_feature_values_finite": bool(
                np.isfinite(
                    matches[
                        [
                            *(f"gt_{feature}" for feature in FEATURE_NAMES),
                            *(f"pred_{feature}" for feature in FEATURE_NAMES),
                        ]
                    ].to_numpy(dtype=float)
                ).all()
            ),
            "stored_deltas_reconcile": all(delta_checks.values()),
            "step9_transitions_reconcile": all(transition_checks.values()),
            "common_subset_support_reconciles": len(common_matches) == len(common_keys),
        }
        if not all(checks.values()):
            raise ValueError(f"Morphology-domain validation failed for {system}: {checks}")
        validations[system] = {
            **checks,
            "feature_delta_checks": delta_checks,
            "transition_checks": transition_checks,
        }

    summary_frame = pd.DataFrame(summary_rows)
    summary_frame["system"] = pd.Categorical(
        summary_frame["system"], categories=SYSTEM_ORDER, ordered=True
    )
    summary_frame["feature"] = pd.Categorical(
        summary_frame["feature"], categories=FEATURE_NAMES, ordered=True
    )
    summary_frame = summary_frame.sort_values(["system", "feature"], kind="stable").reset_index(drop=True)
    summary_frame["system"] = summary_frame["system"].astype("object")
    summary_frame["feature"] = summary_frame["feature"].astype("object")
    paired_frame = pd.DataFrame(paired_rows)
    common_summary_frame = pd.DataFrame(common_summary_rows)
    common_summary_frame["system"] = pd.Categorical(
        common_summary_frame["system"], categories=SYSTEM_ORDER, ordered=True
    )
    common_summary_frame["feature"] = pd.Categorical(
        common_summary_frame["feature"], categories=FEATURE_NAMES, ordered=True
    )
    common_summary_frame = common_summary_frame.sort_values(
        ["system", "feature"], kind="stable"
    ).reset_index(drop=True)
    common_summary_frame["system"] = common_summary_frame["system"].astype("object")
    common_summary_frame["feature"] = common_summary_frame["feature"].astype("object")

    output_dir.mkdir(parents=True, exist_ok=True)
    summary_path = output_dir / "feature_shift_summary.csv"
    paired_path = output_dir / "paired_feature_differences.csv"
    common_summary_path = output_dir / "common_subset_feature_shift_summary.csv"
    tex_path = output_dir / "median_relative_shift_table.tex"
    json_path = output_dir / "analysis_summary.json"
    summary_frame.to_csv(summary_path, index=False, lineterminator="\n", float_format="%.10g")
    paired_frame.to_csv(paired_path, index=False, lineterminator="\n", float_format="%.10g")
    common_summary_frame.to_csv(
        common_summary_path, index=False, lineterminator="\n", float_format="%.10g"
    )
    tex_path.write_text(build_tex_table(summary_frame), encoding="utf-8", newline="\n")

    systematic = summary_frame.loc[summary_frame["descriptively_systematic"]]
    write_json(
        json_path,
        {
            "schema_version": "1.0",
            "sequence": sequence,
            "analysis": "paired morphology domain shift from ground-truth to predicted masks",
            "common_subset": {
                "matched_gt_instances": len(common_keys),
                "purpose": "secondary cross-method sensitivity check on annotated objects matched by all three systems",
            },
            "systematic_direction_rule": {
                "threshold": SYSTEMATIC_DIRECTION_THRESHOLD,
                "definition": "descriptive flag when at least 75% of paired differences share one sign; not a hypothesis test or independent-experiment inference",
            },
            "descriptively_systematic_features": {
                system: systematic.loc[systematic["system"] == system, [
                    "feature",
                    "dominant_direction",
                    "direction_consistency",
                    "median_relative_difference_percent",
                ]].to_dict(orient="records")
                for system in SYSTEM_ORDER
            },
            "validations": validations,
            "interpretation_limits": [
                "Matched MI05 objects are temporally and spatially related and are not independent experiments.",
                "Relative differences for eccentricity can be sensitive to small ground-truth values; raw signed and absolute differences remain available.",
                "Observed feature shifts do not by themselves identify the segmentation mechanism or establish biological change.",
                "The classifier was trained on ground-truth morphology, so predicted-mask feature distributions constitute an input-domain shift.",
            ],
        },
    )

    output_paths = (summary_path, paired_path, common_summary_path, tex_path, json_path)
    write_json(
        output_dir / "analysis_manifest.json",
        {
            "schema_version": "1.0",
            "status": "verified paired MI05 morphology-domain shift analysis",
            "sequence": sequence,
            "command": [str(Path(sys.argv[0]).resolve()), *sys.argv[1:]],
            "script": {
                "path": str(Path(__file__).resolve()),
                "sha256": sha256_file(Path(__file__).resolve()),
            },
            "packages": package_versions(),
            "inputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in sorted(input_paths)
            ],
            "outputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in output_paths
            ],
            "actions_performed": {
                "model_inference": False,
                "classifier_fitting": False,
                "threshold_tuning": False,
                "feature_selection": False,
            },
        },
    )


if __name__ == "__main__":
    main()
