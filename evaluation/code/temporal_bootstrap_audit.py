"""Audit MI05 temporal dependence and moving-block bootstrap sensitivity.

This command reads accepted per-frame evaluation outputs. It performs no model
inference, training, threshold tuning, or configuration selection.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import pandas as pd

from code.unified_evaluation import (
    DetectionCounts,
    detection_metrics,
    package_versions,
    sha256_file,
    write_json,
)


SYSTEM_ORDER = ("stardist_saved", "cellpose_auto", "cellpose_fixed")
DISPLAY_NAMES = {
    "stardist_saved": "StarDist",
    "cellpose_auto": "Cellpose automatic",
    "cellpose_fixed": "Cellpose fixed",
}
BOOTSTRAP_METRICS = ("precision", "recall", "f1", "matched_iou", "pq")
SYSTEM_ACF_QUANTITIES = ("f1", "pred_total", "fn", "matched_iou")
ANNOTATION_ACF_QUANTITIES = ("gt_total", "gt_mitotic_ratio")


def sample_indices(
    rng: np.random.Generator,
    n_frames: int,
    block_length: int,
) -> np.ndarray:
    """Sample non-circular moving blocks and truncate to the original length."""
    if block_length < 1 or block_length > n_frames:
        raise ValueError("block length must be between 1 and the number of frames")
    n_blocks = int(math.ceil(n_frames / block_length))
    starts = rng.integers(0, n_frames - block_length + 1, size=n_blocks)
    sampled = np.concatenate(
        [np.arange(start, start + block_length, dtype=int) for start in starts]
    )
    return sampled[:n_frames]


def pooled_from_rows(frame: pd.DataFrame, indices: np.ndarray) -> dict[str, float | int | None]:
    selected = frame.iloc[indices]
    counts = DetectionCounts(
        tp=int(selected["tp"].sum()),
        fp=int(selected["fp"].sum()),
        fn=int(selected["fn"].sum()),
        matched_iou_sum=float(selected["matched_iou_sum"].sum()),
        matched_iou_count=int(selected["matched_iou_count"].sum()),
    )
    return detection_metrics(counts)


def autocorrelation(values: np.ndarray, max_lag: int) -> np.ndarray:
    """Return the global-mean normalized sample autocorrelation through max_lag."""
    values = np.asarray(values, dtype=float)
    if values.ndim != 1 or len(values) <= max_lag:
        raise ValueError("values must be one-dimensional and longer than max_lag")
    if not np.isfinite(values).all():
        raise ValueError("autocorrelation input contains non-finite values")
    centered = values - values.mean()
    denominator = float(np.dot(centered, centered))
    if denominator == 0:
        raise ValueError("autocorrelation is undefined for a constant series")
    return np.asarray(
        [float(np.dot(centered[lag:], centered[: len(values) - lag]) / denominator) for lag in range(max_lag + 1)]
    )


def first_lag(values: np.ndarray, predicate: Any) -> int | None:
    for lag, value in enumerate(values[1:], start=1):
        if predicate(float(value)):
            return lag
    return None


def build_tex_table(frame: pd.DataFrame, chosen_block_length: int) -> str:
    lines = [
        "% Generated by code/temporal_bootstrap_audit.py from accepted MI05 frame metrics.",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Method & Block & F1 & 2.5th percentile & 97.5th percentile & Width \\\\",
        "\\midrule",
    ]
    subset = frame.loc[frame["metric"] == "f1"]
    for system_index, system in enumerate(SYSTEM_ORDER):
        system_rows = subset.loc[subset["system"] == system].sort_values("block_length")
        for row in system_rows.itertuples(index=False):
            marker = "*" if row.block_length == chosen_block_length else ""
            lines.append(
                f"{DISPLAY_NAMES[system]} & {row.block_length:d}{marker} & "
                f"{row.point_estimate:.3f} & {row.percentile_2_5:.3f} & "
                f"{row.percentile_97_5:.3f} & {row.interval_width:.3f} \\\\" 
            )
        if system_index < len(SYSTEM_ORDER) - 1:
            lines.append("\\addlinespace")
    lines.extend(
        (
            "\\bottomrule",
            "\\end{tabular}",
            "% * Data-informed reporting choice. Intervals describe within-MI05 temporal variability only.",
        )
    )
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-root", required=True)
    parser.add_argument("--sequence", default="MI05")
    parser.add_argument("--block-length", action="append", required=True, type=int)
    parser.add_argument("--chosen-block-length", required=True, type=int)
    parser.add_argument("--replicates", default=2000, type=int)
    parser.add_argument("--seed", default=42, type=int)
    parser.add_argument("--max-lag", default=15, type=int)
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args(argv)

    root = Path(args.results_root).resolve()
    output_dir = Path(args.output_dir).resolve()
    sequence = args.sequence.upper()
    block_lengths = sorted(set(args.block_length))
    if args.chosen_block_length not in block_lengths:
        raise ValueError("chosen block length must be one of the evaluated block lengths")
    if args.replicates < 1:
        raise ValueError("replicates must be positive")

    frames: dict[str, pd.DataFrame] = {}
    input_paths: list[Path] = []
    expected_frame_ids: list[str] | None = None
    for system in SYSTEM_ORDER:
        path = root / system / "metrics_by_frame.csv"
        frame = pd.read_csv(path).sort_values("frame_id", kind="stable")
        frame = frame.loc[frame["frame_id"].str.startswith(f"{sequence}_")].reset_index(drop=True)
        frame_ids = frame["frame_id"].tolist()
        if len(frame_ids) != 69:
            raise ValueError(f"Expected 69 {sequence} frames for {system}, found {len(frame_ids)}")
        if expected_frame_ids is None:
            expected_frame_ids = frame_ids
        elif frame_ids != expected_frame_ids:
            raise ValueError(f"Frame order differs for {system}")
        frames[system] = frame
        input_paths.append(path)

    assert expected_frame_ids is not None
    reference = frames[SYSTEM_ORDER[0]]
    for system in SYSTEM_ORDER[1:]:
        for column in ANNOTATION_ACF_QUANTITIES:
            if not np.allclose(reference[column], frames[system][column], rtol=0, atol=0):
                raise ValueError(f"Annotation series {column} differs for {system}")

    acf_rows: list[dict[str, Any]] = []
    acf_characteristics: list[dict[str, Any]] = []
    series_specs: list[tuple[str, str, np.ndarray]] = []
    for quantity in ANNOTATION_ACF_QUANTITIES:
        series_specs.append(("ground_truth", quantity, reference[quantity].to_numpy(dtype=float)))
    for system in SYSTEM_ORDER:
        for quantity in SYSTEM_ACF_QUANTITIES:
            series_specs.append((system, quantity, frames[system][quantity].to_numpy(dtype=float)))

    for system, quantity, values in series_specs:
        acf = autocorrelation(values, args.max_lag)
        for lag, value in enumerate(acf):
            acf_rows.append(
                {
                    "system": system,
                    "quantity": quantity,
                    "lag_frames": lag,
                    "autocorrelation": value,
                }
            )
        acf_characteristics.append(
            {
                "system": system,
                "quantity": quantity,
                "lag_1": float(acf[1]),
                "first_lag_abs_below_0_2": first_lag(acf, lambda value: abs(value) < 0.2),
                "first_nonpositive_lag": first_lag(acf, lambda value: value <= 0),
            }
        )

    replicate_rows: list[dict[str, Any]] = []
    interval_rows: list[dict[str, Any]] = []
    for block_length in block_lengths:
        if block_length > len(expected_frame_ids):
            raise ValueError(f"Block length {block_length} exceeds the number of frames")
        rng = np.random.default_rng(args.seed)
        sampled_indices = [
            sample_indices(rng, len(expected_frame_ids), block_length)
            for _ in range(args.replicates)
        ]
        for system in SYSTEM_ORDER:
            point = pooled_from_rows(frames[system], np.arange(len(expected_frame_ids)))
            system_rows: list[dict[str, Any]] = []
            for replicate, indices in enumerate(sampled_indices):
                metrics = pooled_from_rows(frames[system], indices)
                row = {
                    "system": system,
                    "block_length": block_length,
                    "replicate": replicate,
                    **{name: metrics[name] for name in BOOTSTRAP_METRICS},
                }
                replicate_rows.append(row)
                system_rows.append(row)
            replicate_frame = pd.DataFrame(system_rows)
            for metric in BOOTSTRAP_METRICS:
                lower = float(replicate_frame[metric].quantile(0.025))
                upper = float(replicate_frame[metric].quantile(0.975))
                interval_rows.append(
                    {
                        "system": system,
                        "block_length": block_length,
                        "metric": metric,
                        "point_estimate": point[metric],
                        "percentile_2_5": lower,
                        "percentile_97_5": upper,
                        "interval_width": upper - lower,
                        "chosen_for_reporting": block_length == args.chosen_block_length,
                    }
                )

    acf_frame = pd.DataFrame(acf_rows)
    replicate_frame = pd.DataFrame(replicate_rows)
    interval_frame = pd.DataFrame(interval_rows)
    output_dir.mkdir(parents=True, exist_ok=True)
    acf_path = output_dir / "autocorrelation.csv"
    replicate_path = output_dir / "bootstrap_replicates.csv"
    interval_path = output_dir / "bootstrap_interval_sensitivity.csv"
    tex_path = output_dir / "bootstrap_interval_table.tex"
    summary_path = output_dir / "analysis_summary.json"
    acf_frame.to_csv(acf_path, index=False, lineterminator="\n", float_format="%.10g")
    replicate_frame.to_csv(replicate_path, index=False, lineterminator="\n", float_format="%.10g")
    interval_frame.to_csv(interval_path, index=False, lineterminator="\n", float_format="%.10g")
    tex_path.write_text(
        build_tex_table(interval_frame, args.chosen_block_length),
        encoding="utf-8",
        newline="\n",
    )

    chosen_f1 = interval_frame.loc[
        (interval_frame["metric"] == "f1")
        & (interval_frame["block_length"] == args.chosen_block_length)
    ]
    write_json(
        summary_path,
        {
            "schema_version": "1.0",
            "sequence": sequence,
            "n_frames": len(expected_frame_ids),
            "rationale_audit": {
                "original_block_length": 7,
                "finding": "The project plan specified 7 but recorded no literature citation, autocorrelation calculation, or selection rule.",
                "classification": "undocumented pragmatic choice",
            },
            "autocorrelation": {
                "max_lag": args.max_lag,
                "estimator": "sum((x[t]-mean)*(x[t-lag]-mean)) divided by sum((x[t]-mean)^2)",
                "characteristics": acf_characteristics,
                "interpretation": "descriptive finite-sequence diagnostics; trends or nonstationarity may contribute to persistence",
            },
            "bootstrap": {
                "method": "non-circular moving-block frame bootstrap",
                "candidate_block_lengths": block_lengths,
                "chosen_block_length": args.chosen_block_length,
                "selection_rule": "Use 10 frames because F1 autocorrelation first falls below an absolute value of 0.2 by lag 7 for StarDist and lag 9 for both Cellpose configurations; 10 is the shortest evaluated length that covers all three F1 decay points.",
                "diagnostic_block_length": 14,
                "diagnostic_reason": "Annotation counts, annotated mitotic ratio, and false negatives decay more slowly; 14 is reported as sensitivity, not selected, because it leaves only about five nonoverlapping block lengths in 69 frames.",
                "replicates": args.replicates,
                "seed": args.seed,
                "sampling_alignment": "Each replicate uses the same sampled frame indices for every system within a block length.",
                "interval": "2.5th and 97.5th percentiles",
                "chosen_f1_intervals": {
                    row.system: {
                        "point_estimate": row.point_estimate,
                        "percentile_2_5": row.percentile_2_5,
                        "percentile_97_5": row.percentile_97_5,
                        "interval_width": row.interval_width,
                    }
                    for row in chosen_f1.itertuples(index=False)
                },
            },
            "scope_statement": "These bootstrap intervals represent temporal variability within MI05. They do not directly estimate performance uncertainty across independent experiments or cell lines.",
        },
    )

    output_paths = (acf_path, replicate_path, interval_path, tex_path, summary_path)
    write_json(
        output_dir / "analysis_manifest.json",
        {
            "schema_version": "1.0",
            "status": "verified descriptive temporal-dependence and bootstrap-sensitivity audit",
            "sequence": sequence,
            "command": [str(Path(sys.argv[0]).resolve()), *sys.argv[1:]],
            "script": {
                "path": str(Path(__file__).resolve()),
                "sha256": sha256_file(Path(__file__).resolve()),
            },
            "packages": package_versions(),
            "inputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in sorted(input_paths)
            ],
            "outputs": [
                {"path": str(path.resolve()), "sha256": sha256_file(path)}
                for path in output_paths
            ],
            "prohibited_actions": {
                "model_inference": False,
                "model_training": False,
                "threshold_tuning": False,
            },
        },
    )


if __name__ == "__main__":
    main()
